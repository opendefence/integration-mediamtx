"""Render the mediamtx-operator overlay from Cloudcoil's runtime RBAC and controllers."""

import argparse
from pathlib import Path

import yaml

from opendefence_integration_mediamtx.operator import create_operator

ROOT = Path(__file__).resolve().parents[1]
NAMESPACE = "integration-mediamtx"
OUTPUT = ROOT / "manifests/operator/operator.yaml.tmpl"


def render() -> str:
    image = "zarf.internal/opendefence/integration-mediamtx:{{ .Pkg.Metadata.Version }}"
    documents = create_operator(namespace=NAMESPACE).manifests(image=image, command=["mediamtx-operator"])
    deployment = next(document for document in documents if document["kind"] == "Deployment")
    pod = deployment["spec"]["template"]["spec"]
    pod["securityContext"] = {
        "runAsNonRoot": True,
        "runAsUser": 65532,
        "runAsGroup": 65532,
        "seccompProfile": {"type": "RuntimeDefault"},
    }
    pod["volumes"] = [
        {"name": "runtime-tmp", "emptyDir": {"medium": "Memory", "sizeLimit": "16Mi"}},
        {"name": "auth-tls", "secret": {"secretName": "mediamtx-auth-tls"}},  # pragma: allowlist secret
    ]
    container = pod["containers"][0]
    container.update(
        volumeMounts=[{"name": "runtime-tmp", "mountPath": "/tmp"}],  # nosec B108 # Pod-only memory volume.
        ports=[{"name": "health", "containerPort": 8080}],
        readinessProbe={"httpGet": {"path": "/readyz", "port": "health"}},
        livenessProbe={"httpGet": {"path": "/healthz", "port": "health"}},
        resources={"requests": {"cpu": "50m", "memory": "64Mi"}, "limits": {"memory": "256Mi"}},
        securityContext={
            "allowPrivilegeEscalation": False,
            "readOnlyRootFilesystem": True,
            "capabilities": {"drop": ["ALL"]},
        },
    )
    pod["containers"].append(
        {
            "name": "auth",
            "image": image,
            "command": ["mediamtx-auth"],
            "args": ["--host", "0.0.0.0", "--tls-cert", "/tls/tls.crt", "--tls-key", "/tls/tls.key"],  # nosec B104
            "env": container["env"],
            "ports": [{"name": "auth", "containerPort": 9443}],
            "volumeMounts": [
                {"name": "auth-tls", "mountPath": "/tls", "readOnly": True},
                {"name": "runtime-tmp", "mountPath": "/tmp"},  # nosec B108 # Pod-only memory volume.
            ],
            "readinessProbe": {"tcpSocket": {"port": "auth"}},
            "livenessProbe": {"tcpSocket": {"port": "auth"}},
            "resources": {"requests": {"cpu": "50m", "memory": "64Mi"}, "limits": {"memory": "256Mi"}},
            "securityContext": container["securityContext"],
        }
    )
    generated = yaml.safe_dump_all(documents, sort_keys=False, width=120)
    generated = generated.replace(f"namespace: {NAMESPACE}", "namespace: {{ .Values.namespace }}")
    generated = generated.replace(f"mediamtx-operator.{NAMESPACE}", "mediamtx-operator.{{ .Values.namespace }}")
    return "# Generated by `task package:render`; do not edit.\n" + generated


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the committed overlay is stale")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            raise SystemExit("Operator overlay is stale; run task package:render")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(generated)


if __name__ == "__main__":
    main()
